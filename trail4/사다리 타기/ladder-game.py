n, m = map(int, input().split())
edges = [tuple(map(int, input().split())) for _ in range(m)]

# Please write your code here.
# -------------------------------------------------
# 1. 가로줄은 높이 순서대로 만나기 때문에
#    b가 작은 순서대로 정렬
# -------------------------------------------------
edges.sort(key=lambda x: (x[1], x[0]))

lines = edges
# print(edges)


# -------------------------------------------------
# 2. 특정 가로줄들을 사용했을 때
#    최종적으로 사다리가 어떻게 되는지 계산
# -------------------------------------------------
def get_result(selected):

    # 처음에는
    #
    # 세로줄 1 → 1
    # 세로줄 2 → 2
    # 세로줄 3 → 3
    # ...
    #
    # 예: n = 4
    # [1, 2, 3, 4]
    arr = list(range(1, n + 1)) ## 시작


    # 높이가 작은 가로줄부터 하나씩 적용
    for a, b in selected:

        # 문제에서는 세로줄 번호가 1부터 시작
        #
        # a = 2라면
        # 2번 세로줄과 3번 세로줄을 연결
        #
        # 리스트 인덱스로는
        # 1번 인덱스와 2번 인덱스
        #
        # 그래서 a-1, a
        left = a - 1
        right = a

        # 가로줄을 만나면 두 값의 위치가 바뀜
        arr[left], arr[right] = arr[right], arr[left]

    return arr

# -------------------------------------------------
# 3. 모든 가로줄을 사용했을 때의 결과
# -------------------------------------------------
#
# 우리가 앞으로 일부 가로줄만 골라서
# 이 target과 똑같은 결과를 만들 수 있는지 확인할 것
#
target = get_result(lines)



# 처음에는 모든 m개의 가로줄을 사용하면
# 당연히 target과 같으므로 답의 최댓값은 m
answer = m


# -------------------------------------------------
# 4. 조합 DFS
#
# index    : 다음에 몇 번째 가로줄부터 고를 것인가
# selected : 지금까지 선택한 가로줄들
# -------------------------------------------------
def dfs(index, selected):
    global answer


    # ---------------------------------------------
    # 지금까지 고른 가로줄들로 사다리를 실행해봄
    # ---------------------------------------------
    current_result = get_result(selected)


    # 원래 전체 사다리의 결과와 같다면
    if current_result == target:

        # 사용한 가로줄 개수의 최소값 갱신
        answer = min(answer, len(selected))

        # 여기서 더 가로줄을 추가하면
        # len(selected)가 더 커지므로
        # 최소 개수를 찾는 데 도움이 안 됨
        return


    # 이미 현재 answer 이상을 골랐다면
    # 더 추가해봐야 최소값이 될 수 없음
    if len(selected) >= answer:
        return


    # ---------------------------------------------
    # 다음에 사용할 가로줄 선택
    #
    # range(index, m)를 쓰는 이유:
    # 조합이기 때문
    #
    # A를 골랐다면 그 다음에는
    # A보다 뒤에 있는 B, C, D...만 고름
    #
    # AB와 BA를 둘 다 볼 필요 없음
    # ---------------------------------------------
    for i in range(index, m):

        # i번째 가로줄 선택
        selected.append(lines[i])


        # 방금 i번을 골랐으므로
        # 다음에는 i+1부터 선택
        dfs(i + 1, selected)


        # 백트래킹
        # 방금 선택했던 가로줄 취소
        selected.pop()


# 아무 가로줄도 선택하지 않은 상태에서 시작
dfs(0, [])

print(answer)