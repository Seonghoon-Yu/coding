# N 층 높이 계산
# 한번에 2계단 혹은 3계단
# N층 높이의 계단에 올라가기 위한 서로 다른 방법의 수.
# N층에서 1개 남으면 올라갈 수없음.

# DP 배열 정의
dp = [0] * (n+1)

# 초기값
if n >= 2:
    dp[2] = 1

if n>= 3:
    dp[3] = 1

if n>= 4:
    dp[4] = 1

