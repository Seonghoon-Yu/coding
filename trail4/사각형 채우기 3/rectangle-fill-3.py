n = int(input())

# Please write your code here.


## DP 배열 정의
dp = [0] * (max(n + 1, 3))

## 초기값
dp[0] = 1
dp[1] = 2
dp[2] = 7

# dp[3] = 16
# dp[4] = 46

### -1 에서 ㅣ 하나 추가인데, ㅁㅁ 도 있어서 2배
### -2 에서 ㅡㅡ 나 ㅣㅣ 추가해서 두배?


### -1 에서 \ 하나 추가 또는 ㅁㅁ 추가하는 방법 # dp[i-1] * 2
### -2 에서 ㅡㅡ 추가하는 방법. ㅡㅁㅁ ㅁㅁㅡ따라서 +dp[i-2] * 3

for i in range(3, n+1):
    ### 슬라이싱은 끝부분을 포함하지 않기 때문에 i-3이 아니라 i-2
    dp[i] = (dp[i-1] * 2 + dp[i-2] * 3 + 2 * sum(dp[:i-2])) % 1_000_000_007

print(dp[n])