# DP 배열 정의
dp = [0] * (N+1)


# 초기값
dp[1] = 1

if N >= 2: ### N=1 이면 dp[2] 에서 error가 남
    dp[2] = 1


# 점화식
## dp[n] = dp[n-1] + dp[n-2]

# 구현
for i in range(3, N+1):
    dp[i] = dp[i-1] + dp[i-2]


print(dp[N])








