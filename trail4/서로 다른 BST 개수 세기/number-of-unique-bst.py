# ==========================================
# 1. DP 배열 정의
# ==========================================
#
# dp[i] =
# 노드가 i개 있을 때 만들 수 있는
# 서로 다른 BST의 개수
#
# 예)
# dp[1] = 노드 1개로 만들 수 있는 BST 개수
# dp[2] = 노드 2개로 만들 수 있는 BST 개수
# dp[3] = 노드 3개로 만들 수 있는 BST 개수
#
dp = [0] * max(4,(n + 1))


# ==========================================
# 2. 초기값
# ==========================================
#
# dp[0] = 1
#
# 노드가 하나도 없는 경우를
# "빈 트리 1가지"라고 생각한다.
#
# 왜 1이냐?
#
# 예를 들어 root가 가장 작은 숫자라면
# 왼쪽 서브트리에는 노드가 0개이다.
#
# 이때
#
# 왼쪽 경우의 수 * 오른쪽 경우의 수
#
# 를 계산해야 하는데
# dp[0]이 0이면 전체 경우가 0이 되어버린다.
#
# 따라서 "아무것도 없는 트리"도
# 하나의 경우로 보고 dp[0] = 1로 둔다.
#
dp[0] = 1


## 점화식

# root가 뭐가 되냐에 따라 오른쪽 왼쪽의 갯수가 달라짐.
# 4
# 3 0 -> dp[3] * dp[0]

# 3
# 2 1 # dp[2] * dp[1]

# 2 
# 1 2 # dp[1] * dp[2]

# 1
# 0 3 # dp[0] * dp[3]

# 왼쪽으로 몇개 남았는지, 오른쪽으로 몇개 남았는지 곱셈


## 구현

for i in range(1, n+1): ### 노트가 i개 일떄의 갯수
    #### i를 돌아가면서 순회
    # print('root', root)
    for left in range(i): ## 왼쪽 갯수 탐색
        # print('remain', remaining)

        right = i-left-1

        dp[i] += dp[left] * dp[right] # 노드가 i개 일떄.


